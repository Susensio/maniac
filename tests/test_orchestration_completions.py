"""A tool's completions through install, update, remove and why (ADR-0066)."""

import stat
from pathlib import Path

import pytest

from maniac import manifest
from maniac.cli.install import completion_shells
from maniac.cli.options import Shell
from maniac.config import Config
from maniac.models import Installation
from maniac.orchestration.completions import (
    completion_for,
    install_completions,
    login_shell,
    recorded_shells,
    remove_tool_completions,
    zsh_fpath_hint,
)
from maniac.orchestration.context import ResolvedTool

_HELP = (
    "Usage: tool [OPTIONS] COMMAND\\n\\nCommands:\\n  completion  Print completions\\n"
)


@pytest.fixture
def cfg(tmp_path: Path) -> Config:
    data = tmp_path / "data"
    return Config(
        manifest_path=tmp_path / "state" / "installed.json",
        completions_output_dir=data / "maniac" / "completions",
        completion_dirs={
            "bash": data / "bash-completion" / "completions",
            "zsh": data / "zsh" / "site-functions",
            "fish": data / "fish" / "vendor_completions.d",
        },
    )


def _tool(tmp_path: Path, cfg: Config, *, root: Path | None = None) -> ResolvedTool:
    """A tool whose --help lists `completion`, which prints a zsh script."""
    binary = tmp_path / "bin" / "tool"
    binary.parent.mkdir(parents=True)
    binary.write_text(
        "#!/bin/sh\n"
        f'case "$1" in --help) printf "{_HELP}";; '
        "completion) [ \"$2\" = zsh ] && printf '#compdef tool\\n' || exit 2;; "
        "esac\n",
        encoding="utf-8",
    )
    binary.chmod(binary.stat().st_mode | stat.S_IXUSR)
    installation = (
        Installation(
            binary="tool",
            bin_path=binary,
            real_path=binary,
            provider="fake",
            package="tool",
            version="1.0",
            root=root,
        )
        if root is not None
        else None
    )
    return ResolvedTool(
        tool_name="tool",
        config=cfg,
        cache_dir=cfg.cache_dir,
        bin_path=binary,
        installation=installation,
    )


def test_a_generated_completion_is_installed_and_recorded(
    tmp_path: Path, cfg: Config
) -> None:
    tool = _tool(tmp_path, cfg)

    [outcome] = install_completions(tool, ("zsh",), dry_run=False)

    assert outcome.installed
    assert outcome.detail == "generated by `tool completion zsh`"
    assert (cfg.completion_dirs["zsh"] / "_tool").read_text().startswith("#compdef")
    assert recorded_shells("tool", cfg) == ("zsh",)


def test_a_shell_with_neither_source_says_why(tmp_path: Path, cfg: Config) -> None:
    tool = _tool(tmp_path, cfg)

    [outcome] = install_completions(tool, ("fish",), dry_run=False)

    assert not outcome.installed
    assert "no fish file" in outcome.detail
    assert recorded_shells("tool", cfg) == ()


def test_a_shipped_completion_comes_before_the_generator(
    tmp_path: Path, cfg: Config
) -> None:
    root = tmp_path / "root"
    shipped = root / "share" / "zsh" / "site-functions" / "_tool"
    shipped.parent.mkdir(parents=True)
    shipped.write_text("#compdef tool\n# shipped\n", encoding="utf-8")

    found = completion_for(_tool(tmp_path, cfg, root=root), "zsh")

    assert found.shipped == shipped


def test_a_dry_run_installs_nothing(tmp_path: Path, cfg: Config) -> None:
    [outcome] = install_completions(_tool(tmp_path, cfg), ("zsh",), dry_run=True)

    assert outcome.installed
    assert not (cfg.completion_dirs["zsh"] / "_tool").exists()


def test_remove_takes_them_out(tmp_path: Path, cfg: Config) -> None:
    install_completions(_tool(tmp_path, cfg), ("zsh",), dry_run=False)

    assert remove_tool_completions("tool", cfg) == ("zsh",)
    assert manifest.completions_of("tool", cfg) == {}


def test_zsh_is_told_the_fpath_line_until_a_startup_file_names_the_directory(
    tmp_path: Path, cfg: Config, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("ZDOTDIR", str(tmp_path / "z"))
    (tmp_path / "z").mkdir()

    hint = zsh_fpath_hint(cfg)
    assert hint is not None
    assert str(cfg.completion_dirs["zsh"]) in hint

    (tmp_path / "z" / ".zshrc").write_text(
        f"fpath=({cfg.completion_dirs['zsh']} $fpath)\nautoload -U compinit\n",
        encoding="utf-8",
    )
    assert zsh_fpath_hint(cfg) is None


@pytest.mark.parametrize(
    ("shell_env", "named", "off", "expected"),
    [
        ("/usr/bin/zsh", None, False, ("zsh",)),
        ("/bin/sh", None, False, ()),
        ("/usr/bin/zsh", [Shell.fish, Shell.bash], False, ("fish", "bash")),
        ("/usr/bin/zsh", None, True, ()),
    ],
)
def test_completions_go_to_the_login_shell_unless_shells_are_named(
    monkeypatch: pytest.MonkeyPatch,
    shell_env: str,
    named: list[Shell] | None,
    off: bool,
    expected: tuple[str, ...],
) -> None:
    monkeypatch.setenv("SHELL", shell_env)

    assert completion_shells(named, no_completions=off) == expected
    assert login_shell() == (Path(shell_env).name if shell_env != "/bin/sh" else None)
