"""Where a tool's shell completion comes from, in order (ADR-0066).

The order is written here once: for each shell, the completion the tool
shipped, else its repository's at the installed version, else the one its
own generator prints, else the one the shell's own parser derives from the
page maniac installed or the tool's --help (`completion_for`). `install`
links what it finds, `why` explains it, and `scan` reports it.
"""

import os
from dataclasses import dataclass
from pathlib import Path

from ...config import Config
from ...exceptions import CrawlerError
from ...models import Installation
from ..completions import (
    SHELLS,
    Ambiguous,
    Derived,
    Generated,
    derived_completion,
    generated_completion,
    shipped_completion,
)
from ..crawler import extract_subcommands, get_help
from ..docs.completions import Upstream, upstream_completion
from ..providers.base import Provider
from .candidates import repository_of


def login_shell() -> str | None:
    """The completion shell `$SHELL` names, or None for one maniac has none for."""
    name = Path(os.environ.get("SHELL") or "").name
    return name if name in SHELLS else None


@dataclass(frozen=True, slots=True)
class Subject:
    """The binary whose completion is looked up, and what is known about it.

    `name` is the binary's own name, which its completion is named after.
    `executable` is what runs for its `--help`: its path whenever one resolved.
    `page` is the page maniac installed for it, which fish's parser reads.
    """

    name: str
    executable: str
    config: Config
    cache_dir: Path
    bin_path: Path | None = None
    installation: Installation | None = None
    provider: Provider | None = None
    page: Path | None = None


@dataclass(frozen=True, slots=True)
class Found:
    """Where one shell's completion would come from, or why there is none."""

    shell: str
    shipped: Path | None = None
    upstream: Upstream | None = None
    upstream_from: str | None = None
    """The repository and tag asked, as `why` names them."""
    generated: Generated | None = None
    derived: Derived | None = None
    none_because: str | None = None
    complete: bool = True
    """False when a check that could have answered did not finish (rule 4)."""

    @property
    def source(self) -> str | None:
        """The source's name, as the contract's table names it; None if none."""
        for name in ("shipped", "upstream", "generated", "derived"):
            if getattr(self, name) is not None:
                return name
        return None

    def describe(self, tool: str) -> str:
        if self.shipped is not None:
            return f"shipped, {_home(self.shipped)}"
        if self.upstream is not None:
            return f"upstream, {self.upstream.uri or self.upstream_from}"
        if self.generated is not None:
            return f"generated by `{tool} {' '.join(self.generated.arguments)}`"
        if self.derived is not None:
            return f"derived by {self.derived.how}"
        return f"none: {self.none_because}"


class Help:
    """The tool's root `--help`, crawled once for every shell asked about."""

    def __init__(self, subject: Subject) -> None:
        self._subject = subject
        self._text: tuple[str, list[str]] | None = None

    def get(self) -> tuple[str, list[str]] | None:
        if self._text is None:
            try:
                text = get_help([self._subject.executable], config=self._subject.config)
            except CrawlerError:
                text = ""
            self._text = (text, extract_subcommands(text, self._subject.name))
        return self._text if self._text[0] else None


def completion_for(subject: Subject, shell: str, help_: Help | None = None) -> Found:
    """`subject`'s completion for `shell`: shipped, else its repository's at the
    installed version, else its own generator, else derived."""
    inst = subject.installation
    name = subject.name
    # Why an earlier source gave nothing, said when no later one answers.
    passed_over: list[str] = []
    complete = True
    if inst is not None:
        shipped = shipped_completion(inst.root, name, shell)
        if isinstance(shipped, Ambiguous):
            passed_over.append(f"its install root has {shipped}")
        elif shipped is not None:
            return Found(shell, shipped=shipped)
    if inst is not None and subject.provider is not None:
        source = repository_of(subject.provider, inst, subject.config).source
        if source is not None:
            upstream, definitive = upstream_completion(
                source,
                name,
                shell,
                version=inst.version,
                cache_dir=subject.cache_dir,
                config=subject.config,
            )
            if isinstance(upstream, Ambiguous):
                passed_over.append(
                    f"{source.identity} at {inst.version} has {upstream}"
                )
            elif upstream is not None:
                return Found(
                    shell,
                    upstream=upstream,
                    upstream_from=f"{source.identity} at {inst.version}",
                )
            if not definitive:
                complete = False
                passed_over.append("the upstream check did not complete")
    help_ = help_ or Help(subject)
    found = _generated(subject, shell, help_)
    if found.none_because is not None:
        crawled = help_.get()
        derived = derived_completion(
            shell,
            name,
            help_text=crawled[0] if crawled is not None else "",
            page=subject.page,
            timeout=subject.config.timeout_help,
        )
        if derived is not None:
            return Found(shell, derived=derived)
    if found.none_because is not None and passed_over:
        return Found(
            shell,
            none_because="; ".join([found.none_because, *passed_over]),
            complete=complete,
        )
    return found


def _generated(subject: Subject, shell: str, help_: Help) -> Found:
    """What the tool's own generator prints for `shell`, or why nothing."""
    if subject.bin_path is None:
        return Found(shell, none_because="no binary to ask")
    crawled = help_.get()
    if crawled is None:
        return Found(shell, none_because="its --help could not be read")
    text, subcommands = crawled
    generated = generated_completion(
        subject.bin_path,
        subject.name,
        shell,
        help_text=text,
        subcommands=subcommands,
        timeout=subject.config.timeout_help,
    )
    if generated is not None:
        return Found(shell, generated=generated)
    where = (
        "its install root or repository"
        if subject.installation is not None
        else "no install root"
    )
    return Found(
        shell,
        none_because=f"no {shell} file in {where}, and its --help names no generator",
    )


def _home(path: Path) -> str:
    """`path` with the home directory written `~`."""
    try:
        return f"~/{path.relative_to(Path.home())}"
    except ValueError:
        return str(path)
