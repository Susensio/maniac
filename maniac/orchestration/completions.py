"""A tool's shell completions, for `install`, `update`, `remove` and `why` (ADR-0066).

The order is written here once: for each shell, the completion the tool
shipped, else its repository's at the installed version, else the one its
own generator prints (`completion_for`). `install`
links what that finds (`install_completions`), `why` explains it with the
same function, and `remove` unlinks what maniac recorded.

maniac never edits a shell's startup files (CONTRACT.md rule 1): zsh reads
completions only from `$fpath`, so when nothing in the user's zsh startup
files names maniac's directory, `zsh_fpath_hint` says which line to add.
"""

import os
from dataclasses import dataclass
from pathlib import Path

from .. import manifest
from ..completion_files import (
    CompletionTaken,
    install_completion,
    remove_completions,
)
from ..config import Config
from ..exceptions import CrawlerError
from ..sources.completions import (
    SHELLS,
    Ambiguous,
    Generated,
    generated_completion,
    shipped_completion,
)
from ..sources.crawler import extract_subcommands, get_help
from ..sources.docs.completions import Upstream, upstream_completion
from ..sources.lookup.candidates import repository_of
from .context import ResolvedTool


def login_shell() -> str | None:
    """The completion shell `$SHELL` names, or None for one maniac has none for."""
    name = Path(os.environ.get("SHELL") or "").name
    return name if name in SHELLS else None


@dataclass(frozen=True, slots=True)
class Found:
    """Where one shell's completion would come from, or why there is none."""

    shell: str
    shipped: Path | None = None
    upstream: Upstream | None = None
    upstream_from: str | None = None
    """The repository and tag asked, as `why` names them."""
    generated: Generated | None = None
    none_because: str | None = None

    def describe(self, tool: str) -> str:
        if self.shipped is not None:
            return f"shipped, {_home(self.shipped)}"
        if self.upstream is not None:
            return f"upstream, {self.upstream.uri or self.upstream_from}"
        if self.generated is not None:
            return f"generated by `{tool} {' '.join(self.generated.arguments)}`"
        return f"none: {self.none_because}"


class _Help:
    """The tool's root `--help`, crawled once for every shell asked about."""

    def __init__(self, tool: ResolvedTool) -> None:
        self._tool = tool
        self._text: tuple[str, list[str]] | None = None

    def get(self) -> tuple[str, list[str]] | None:
        if self._text is None:
            try:
                text = get_help([self._tool.executable], config=self._tool.config)
            except CrawlerError:
                text = ""
            self._text = (text, extract_subcommands(text, self._tool.tool_name))
        return self._text if self._text[0] else None


def completion_for(tool: ResolvedTool, shell: str, help_: _Help | None = None) -> Found:
    """`tool`'s completion for `shell`: shipped, else its repository's at the
    installed version, else its own generator."""
    inst = tool.installation
    name = inst.binary if inst is not None else tool.tool_name
    # Why an earlier source gave nothing, said when no later one answers.
    passed_over: list[str] = []
    if inst is not None:
        shipped = shipped_completion(inst.root, name, shell)
        if isinstance(shipped, Ambiguous):
            passed_over.append(f"its install root has {shipped}")
        elif shipped is not None:
            return Found(shell, shipped=shipped)
    if inst is not None and tool.provider is not None:
        source = repository_of(tool.provider, inst, tool.config).source
        if source is not None:
            upstream, definitive = upstream_completion(
                source,
                name,
                shell,
                version=inst.version,
                cache_dir=tool.cache_dir,
                config=tool.config,
            )
            if isinstance(upstream, Ambiguous):
                passed_over.append(
                    f"{source.identity} at {inst.version} has {upstream}"
                )
            elif upstream is not None:
                return Found(
                    shell,
                    upstream=upstream,
                    upstream_from=f"{source.identity} at {inst.version}",
                )
            if not definitive:
                passed_over.append("the upstream check did not complete")
    found = _generated(tool, name, shell, help_)
    if found.none_because is not None and passed_over:
        return Found(shell, none_because="; ".join([found.none_because, *passed_over]))
    return found


def _generated(tool: ResolvedTool, name: str, shell: str, help_: _Help | None) -> Found:
    """What the tool's own generator prints for `shell`, or why nothing."""
    inst = tool.installation
    if tool.bin_path is None:
        return Found(shell, none_because="no binary to ask")
    crawled = (help_ or _Help(tool)).get()
    if crawled is None:
        return Found(shell, none_because="its --help could not be read")
    text, subcommands = crawled
    generated = generated_completion(
        tool.bin_path,
        name,
        shell,
        help_text=text,
        subcommands=subcommands,
        timeout=tool.config.timeout_help,
    )
    if generated is not None:
        return Found(shell, generated=generated)
    where = "its install root or repository" if inst is not None else "no install root"
    return Found(
        shell,
        none_because=f"no {shell} file in {where}, and its --help names no generator",
    )


@dataclass(frozen=True, slots=True)
class CompletionOutcome:
    """What `install` did, or would do, about one shell."""

    shell: str
    detail: str
    installed: bool


def install_completions(
    tool: ResolvedTool, shells: tuple[str, ...], *, dry_run: bool
) -> tuple[CompletionOutcome, ...]:
    """Find and link `tool`'s completion for each shell, in one transaction."""
    if not shells:
        return ()
    help_ = _Help(tool)
    found = [completion_for(tool, shell, help_) for shell in shells]
    name = tool.installation.binary if tool.installation else tool.tool_name
    outcomes = []
    if dry_run:
        return tuple(
            CompletionOutcome(f.shell, f.describe(name), f.none_because is None)
            for f in found
        )
    with manifest.transaction(tool.config) as txn:
        for f in found:
            if f.none_because is not None:
                outcomes.append(CompletionOutcome(f.shell, f.describe(name), False))
                continue
            try:
                install_completion(
                    name,
                    f.shell,
                    shipped=f.shipped,
                    script=_script_of(f),
                    source="upstream" if f.upstream is not None else "generated",
                    arguments=f.generated.arguments if f.generated else (),
                    version=tool.installed_version,
                    txn=txn,
                )
            except CompletionTaken as taken:
                outcomes.append(
                    CompletionOutcome(
                        f.shell,
                        "not installed: a completion maniac did not install is "
                        f"there, {_home(taken.path)}",
                        False,
                    )
                )
                continue
            outcomes.append(CompletionOutcome(f.shell, f.describe(name), True))
    return tuple(outcomes)


def _script_of(found: Found) -> str | None:
    if found.upstream is not None:
        return found.upstream.script
    return found.generated.script if found.generated is not None else None


def recorded_shells(tool: str, config: Config) -> tuple[str, ...]:
    """The shells maniac installed `tool`'s completions for (`update` keeps to them)."""
    return tuple(sorted(manifest.completions_of(tool, config)))


def remove_tool_completions(tool: str, config: Config) -> tuple[str, ...]:
    """Remove `tool`'s completions; the shells they were removed for."""
    with manifest.transaction(config) as txn:
        return remove_completions(tool, txn).removed


def zsh_fpath_hint(config: Config) -> str | None:
    """The line to add when no zsh startup file names maniac's directory."""
    directory = config.completion_dirs["zsh"]
    home = Path(os.environ.get("ZDOTDIR") or Path.home())
    spellings = {str(directory), _home(directory), _xdg_spelling(directory)}
    for name in (".zshrc", ".zshenv", ".zprofile"):
        try:
            text = (home / name).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if any(spelling in text for spelling in spellings if spelling):
            return None
    return (
        f"zsh reads completions only from $fpath: add `fpath=({_home(directory)} "
        "$fpath)` to ~/.zshrc, before `compinit`"
    )


def _xdg_spelling(directory: Path) -> str:
    data = os.environ.get("XDG_DATA_HOME") or str(Path.home() / ".local" / "share")
    try:
        return f"$XDG_DATA_HOME/{directory.relative_to(data)}"
    except ValueError:
        return ""


def _home(path: Path) -> str:
    try:
        return f"~/{path.relative_to(Path.home())}"
    except ValueError:
        return str(path)
