"""Manpage system installation, conflict resolution, uninstallation, and inventory."""

import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .config import Config
from .logging import logger

PROVENANCE_SIGNATURE = r".\" Generated by MANIAC (https://github.com/susensio/maniac)"


def read_provenance_header(file_path: str | Path) -> dict[str, str] | None:
    """Read provenance metadata from the header of a roff manpage file."""
    path = Path(file_path)
    if not path.exists() or not path.is_file():
        return None

    try:
        with path.open("r", encoding="utf-8", errors="replace") as f:
            first_line = f.readline().strip()
            if first_line != PROVENANCE_SIGNATURE:
                return None
            second_line = f.readline().strip()
    except PermissionError:
        # Distinguish "can't read it" from "read it, not ours" -- the caller
        # should not treat a permission failure as a foreign/vendor page.
        logger.warning("Permission denied reading manpage header", path=str(path))
        raise
    except OSError:
        return None

    metadata = {"tool": path.stem, "date": "unknown", "model": "unknown"}
    if second_line.startswith(r".\" "):
        meta_content = second_line[4:].strip()
        for item in meta_content.split("|"):
            parts = item.split(":", 1)
            if len(parts) == 2:
                key = parts[0].strip().lower()
                val = parts[1].strip()
                metadata[key] = val

    return metadata


def install_manpage(
    source_file: str | Path,
    target_dir: str | Path | None = None,
    force: bool = False,
) -> Path:
    """Copy compiled roff manpage into man directory with conflict guard and backup."""
    src = Path(source_file)
    dest_dir = Path(target_dir).expanduser() if target_dir else Config().man_dir
    dest_dir.mkdir(parents=True, exist_ok=True)

    dest_file = dest_dir / src.name

    if dest_file.exists():
        prov = read_provenance_header(dest_file)
        if prov is None:
            if not force:
                raise FileExistsError(
                    f"A foreign or vendor manpage already exists at '{dest_file}'. "
                    f"Use --force to create a backup and overwrite."
                )
            backup_file = dest_file.with_name(f"{dest_file.name}.maniac_bak")
            shutil.copy2(dest_file, backup_file)
            logger.info(
                "Created backup of foreign manpage", backup_file=str(backup_file)
            )

    shutil.copy2(src, dest_file)
    logger.info("Installed manpage", path=str(dest_file))
    return dest_file


@dataclass
class UninstallResult:
    """Outcome of an `uninstall_manpage()` call."""

    removed: list[Path] = field(default_factory=list)
    # Set when a non-MANIAC page occupies the installed slot and was left in place.
    foreign_kept: Path | None = None


def uninstall_manpage(
    tool_name: str,
    purge: bool = False,
    config: Config | None = None,
) -> UninstallResult:
    """Uninstall a MANIAC-generated manpage and restore backups if present."""
    cfg = config or Config()
    removed_paths: list[Path] = []
    foreign_kept: Path | None = None

    # 1. Active installed manpage in man_dir (~/.local/share/man/man1/<tool>.1)
    installed_file = cfg.man_dir / f"{tool_name}.1"
    if installed_file.exists():
        prov = read_provenance_header(installed_file)
        if prov is None:
            foreign_kept = installed_file
        else:
            installed_file.unlink()
            logger.info("Removed installed manpage", path=str(installed_file))

            backup_file = cfg.man_dir / f"{tool_name}.1.maniac_bak"
            if backup_file.exists():
                backup_file.rename(installed_file)
                logger.info("Restored vendor backup manpage", path=str(installed_file))
            else:
                removed_paths.append(installed_file)

    # 2. XDG data storage (output_dir / <tool>.1)
    stored_roff = cfg.output_dir / f"{tool_name}.1"
    if stored_roff.exists():
        stored_roff.unlink()
        removed_paths.append(stored_roff)

    if purge:
        stored_md = cfg.output_dir / f"{tool_name}.1.md"
        if stored_md.exists():
            stored_md.unlink()
            removed_paths.append(stored_md)

        inter_ctx = cfg.intermediate_dir / f"{tool_name}_context.md"
        if inter_ctx.exists():
            inter_ctx.unlink()
            removed_paths.append(inter_ctx)

        inter_prompt = cfg.intermediate_dir / f"{tool_name}_prompt.md"
        if inter_prompt.exists():
            inter_prompt.unlink()
            removed_paths.append(inter_prompt)

    return UninstallResult(removed=removed_paths, foreign_kept=foreign_kept)


def list_installed_manpages(
    config: Config | None = None,
) -> list[dict[str, Any]]:
    """Scan and list all MANIAC-managed manual pages with metadata."""
    cfg = config or Config()
    results: list[dict[str, Any]] = []
    seen_tools: set[str] = set()

    for search_dir in (cfg.man_dir, cfg.output_dir):
        if not search_dir.exists():
            continue
        for file_path in search_dir.glob("*.1"):
            prov = read_provenance_header(file_path)
            if prov is not None:
                tool = prov.get("tool", file_path.stem)
                if tool in seen_tools:
                    continue
                seen_tools.add(tool)

                has_bak = (cfg.man_dir / f"{tool}.1.maniac_bak").exists()
                results.append(
                    {
                        "tool": tool,
                        "path": file_path,
                        "date": prov.get("date", "unknown"),
                        "model": prov.get("model", "unknown"),
                        "has_backup": has_bak,
                    }
                )

    return sorted(results, key=lambda x: x["tool"])
